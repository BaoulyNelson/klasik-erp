export function obtenir_libelle_role_etablissement(
  id_role: IdentifiantRole,
  type: TypeEtablissement
): string {
  if (id_role === 'DIRECTEUR') {
    if (type === 'PRO') return 'Directeur du centre';
    if (type === 'SCOLAIRE') return 'Directeur d’établissement';
    return 'Recteur / Doyen';
  }
  if (id_role === 'ENSEIGNANT') {
    if (type === 'PRO') return 'Formateur';
    if (type === 'SCOLAIRE') return 'Professeur';
    return 'Enseignant-chercheur';
  }
  if (id_role === 'APPRENANT') {
    if (type === 'PRO') return 'Apprenant / Stagiaire';
    if (type === 'SCOLAIRE') return 'Élève';
    return 'Étudiant';
  }
  if (id_role === 'DIR_ETUDES') {
    if (type === 'SCOLAIRE') return 'Préfet de discipline / Dir. Études';
    if (type === 'UNIVERSITE') return 'Vice-recteur académique';
    return 'Responsable pédagogique';
  }
  return (ROLES[id_role] ?? ROLES.DIRECTEUR).libelle;
}
